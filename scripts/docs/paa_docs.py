def render_header(values: dict[str, str]) -> str:
    lines = [f"{field}: {values.get(field, '')}" for field in HEADER_FIELD_ORDER]
    return "\n".join(lines) + "\n\n"


def read_body_without_header(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()
    if not lines:
        return ""
    header_lines, _terminated = read_header_lines(path)
    if header_lines and header_lines[0].partition(":")[0].strip() in ALLOWED_FIELDS:
        consumed = len(header_lines)
        return "\n".join(lines[consumed:]).lstrip("\n")
    return text


def iter_body_lines(text: str) -> Iterable[tuple[int, str]]:
    for idx, line in enumerate(text.splitlines(), start=1):
        yield idx, line


def line_contains_code_path(line: str) -> bool:
    return bool(
        re.search(r"`[^`]+\.(py|ts|js|md|json)`", line)
        or re.search(r"\b[\w./-]+\.(py|ts|js|md|json)\b", line)
        or "packages/" in line
    )


def validate_language_governance(records: list[dict[str, object]], root: Path) -> list[Finding]:
    findings: list[Finding] = []
    for record in records:
        if record.get("header_status") != "valid":
            continue
        rel_path = str(record.get("path"))
        full_path = root / rel_path
        if not full_path.exists():
            continue
        body = read_body_without_header(full_path)
        lower_body = body.lower()
        has_path_classification = any(hint in lower_body for hint in PATH_CLASSIFICATION_HINTS)
        in_code_block = False
        for line_number, line in iter_body_lines(body):
            lower_line = line.lower()
            if line.strip().startswith("```"):
                in_code_block = not in_code_block
                continue
            if in_code_block:
                continue
            if "`" in line:
                skip_phrase_check = True
            else:
                skip_phrase_check = False
            for phrase, guidance in LANGUAGE_BANNED_PHRASES.items():
                if not skip_phrase_check and phrase in lower_line:
                    findings.append(
                        Finding(
                            "warning",
                            "banned_vague_phrase",
                            rel_path,
                            f"Line {line_number}: '{phrase}' is too vague. {guidance}",
                        )
                    )
            words = set(re.findall(r"[a-z]+", lower_line))
            stripped_line = lower_line.strip().rstrip(".!")
            bare_status_match = stripped_line in LANGUAGE_STRONG_STATUS_WORDS
            pronoun_status_match = bool(
                re.match(r"^(this|it|that)\s+(is|was)\s+(" + "|".join(sorted(LANGUAGE_STRONG_STATUS_WORDS)) + r")$", stripped_line)
            )
            if bare_status_match or pronoun_status_match:
                strong_status_hits = words & LANGUAGE_STRONG_STATUS_WORDS
                hit_list = ", ".join(sorted(strong_status_hits))
                findings.append(
                    Finding(
                        "warning",
                        "missing_status_scope",
                        rel_path,
                        f"Line {line_number}: strong status word(s) {hit_list} lack an obvious scope qualifier.",
                    )
                )
            if line_contains_code_path(line) and (words & PATH_CLAIM_TERMS) and not has_path_classification:
                findings.append(
                    Finding(
                        "warning",
                        "missing_path_classification",
                        rel_path,
                        f"Line {line_number}: path or module claim should classify the path as aligned, hybrid, or legacy.",
                    )
                )
    return findings


def load_code_component_registry(root: Path) -> dict[str, object]:
    source_root = root / "packages/paa-core/src"
    if not source_root.exists():
        return {}
    source_root_str = str(source_root)
    added = False
    if source_root_str not in sys.path:
        sys.path.insert(0, source_root_str)
        added = True
    try:
        importlib.invalidate_caches()
        module = importlib.import_module("paa_core.governance.component_registry")
        registry = getattr(module, "COMPONENT_METADATA_BY_NAME", {})
        if isinstance(registry, dict):
            return registry
        return {}
    except Exception:
        return {}
    finally:
        if added:
            try:
                sys.path.remove(source_root_str)
            except ValueError:
                pass


def validate_doc_code_consistency(
    records: list[dict[str, object]],
    root: Path,
    component_registry: dict[str, object] | None = None,
) -> list[Finding]:
    findings: list[Finding] = []
    registry = component_registry if component_registry is not None else load_code_component_registry(root)
    for record in records:
        if record.get("header_status") != "valid":
            continue
        if record.get("authority_source") != "code":
            continue
        rel_path = str(record.get("path"))
        component_name = record.get("component")
        if not isinstance(component_name, str) or not component_name:
            findings.append(
                Finding(
                    "error",
                    "missing_code_component",
                    rel_path,
                    "Document declares Authority-Source: code but does not define a Component header.",
                )
            )
            continue
        if component_name not in registry:
            findings.append(
                Finding(
                    "error",
                    "unmapped_code_component",
                    rel_path,
                    f"Component '{component_name}' does not resolve to an exported governed metadata constant.",
                )
            )
    return findings


