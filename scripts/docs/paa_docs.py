def command_sync_current(args: argparse.Namespace) -> int:
    records, _ = build_index(args.root)
    payload = snapshot_payload(args.root, records, stage=args.stage, doc_id=args.doc_id)
    collisions = [record for record in payload["records"] if record.get("sync_status") == "collision"]
    if collisions:
        if args.format == "json":
            print_json(payload)
        else:
            print(render_snapshot_table(payload))
        return 1

    managed_current_paths = {str(record["current_path"]) for record in payload["records"]}
    planned_creates: list[str] = []
    planned_updates: list[str] = []
    for record in payload["records"]:
        current_path = args.root / str(record["current_path"])
        rendered = render_generated_current_copy({"path": record["source_path"]}, args.root)
        if not current_path.exists():
            planned_creates.append(str(record["current_path"]))
            if not args.dry_run:
                current_path.parent.mkdir(parents=True, exist_ok=True)
                current_path.write_text(rendered, encoding="utf-8")
            continue
        existing = current_path.read_text(encoding="utf-8")
        if existing != rendered:
            planned_updates.append(str(record["current_path"]))
            if not args.dry_run:
                current_path.parent.mkdir(parents=True, exist_ok=True)
                current_path.write_text(rendered, encoding="utf-8")

    pruned_paths: list[str] = []
    if args.prune:
        stage_roots = [root for root in CURRENT_TAXONOMY if args.stage is None or detect_stage_from_path(Path(root)) == args.stage]
        for stage_root in stage_roots:
            current_root = args.root / stage_root / CURRENT_DIR_NAME
            if not current_root.exists():
                continue
            for path in sorted(current_root.rglob("*.md")):
                rel_path = repo_relative(path, args.root)
                if rel_path in managed_current_paths:
                    continue
                pruned_paths.append(rel_path)
                if not args.dry_run:
                    path.unlink()

    summary = {
        "ok": True,
        "dry_run": args.dry_run,
        "created": planned_creates,
        "updated": planned_updates,
        "pruned": pruned_paths,
        "record_count": len(payload["records"]),
    }
    if args.format == "json":
        print_json(summary)
    else:
        print_json(summary) if args.format == "table" and False else print(
            "\n".join(
                [
                    f"ok: {summary['ok']}",
                    f"dry_run: {summary['dry_run']}",
                    f"record_count: {summary['record_count']}",
                    f"created: {len(planned_creates)}",
                    f"updated: {len(planned_updates)}",
                    f"pruned: {len(pruned_paths)}",
                ]
            )
        )
    return 0


