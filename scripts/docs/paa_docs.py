def read_header_lines(path: Path) -> tuple[list[str], bool]:
    lines: list[str] = []
    with path.open("r", encoding="utf-8") as handle:
        for _ in range(HEADER_LINE_LIMIT):
            line = handle.readline()
            if line == "":
                break
            lines.append(line.rstrip("\n"))
            if line.strip() == "":
                return lines, True
    return lines, False


def parse_header(path: Path, root: Path) -> tuple[dict[str, object] | None, list[Finding]]:
    rel_path = repo_relative(path, root)
    lines, terminated = read_header_lines(path)
    findings: list[Finding] = []
    if not lines:
        findings.append(Finding("info", "legacy_missing_header", rel_path, "Document is empty or missing a header."))
        return None, findings
    header_lines: list[str] = []
    for line in lines:
        if line.strip() == "":
            break
        header_lines.append(line)
    if not header_lines:
        findings.append(Finding("info", "legacy_missing_header", rel_path, "Document does not begin with a super header."))
        return None, findings
    first_key, first_sep, _first_value = header_lines[0].partition(":")
    if not first_sep or first_key.strip() not in ALLOWED_FIELDS:
        findings.append(Finding("info", "legacy_missing_header", rel_path, "Document does not begin with a governed super header."))
        return None, findings
    if not terminated:
        findings.append(Finding("error", "header_too_long", rel_path, f"Header did not terminate with a blank line within {HEADER_LINE_LIMIT} lines."))
    raw: dict[str, str] = {}
    seen: set[str] = set()
    for line in header_lines:
        key, sep, value = line.partition(":")
        if not sep:
            findings.append(Finding("error", "invalid_header", rel_path, "Header contains malformed lines; expected 'Key: Value'."))
            return None, findings
        key = key.strip()
        value = value.lstrip()
        if key in seen:
            findings.append(Finding("error", "duplicate_field", rel_path, f"Duplicate header field: {key}"))
            continue
        seen.add(key)
        raw[key] = value.strip()
    unknown_fields = sorted(set(raw) - ALLOWED_FIELDS)
    for field in unknown_fields:
        findings.append(Finding("error", "unknown_field", rel_path, f"Unknown header field: {field}"))
    for field in REQUIRED_FIELDS:
        if field not in raw:
            findings.append(Finding("error", "missing_required_field", rel_path, f"Missing required field: {field}"))
    record = normalize_record(raw, rel_path)
    findings.extend(validate_normalized_record(record))
    if any(f.severity == "error" for f in findings):
        record["header_status"] = "invalid_header"
    else:
        record["header_status"] = "valid"
    return record, findings


def normalize_list(value: str) -> list[str]:
    return [item.strip() for item in value.split(",") if item.strip()]


def normalize_record(raw: dict[str, str], rel_path: str) -> dict[str, object]:
    record: dict[str, object] = {
        "path": rel_path,
        "header_status": "valid",
    }
    for key, value in raw.items():
        normalized_key = key.lower().replace("-", "_")
        if key in LIST_FIELDS:
            record[normalized_key] = normalize_list(value)
        elif key == "Canonical":
            record[normalized_key] = value.lower() == "true"
        else:
            record[normalized_key] = value
    return record


def validate_normalized_record(record: dict[str, object]) -> list[Finding]:
    rel_path = str(record.get("path", ""))
    findings: list[Finding] = []
    doc_type = record.get("doc_type")
    if isinstance(doc_type, str) and doc_type not in DOC_TYPE_VALUES:
        findings.append(Finding("error", "invalid_doc_type", rel_path, f"Invalid Doc-Type: {doc_type}"))
    status = record.get("status")
    if isinstance(status, str) and status not in STATUS_VALUES:
        findings.append(Finding("error", "invalid_status", rel_path, f"Invalid Status: {status}"))
    stage = record.get("lifecycle_stage")
    if isinstance(stage, str) and stage not in LIFECYCLE_VALUES:
        findings.append(Finding("error", "invalid_lifecycle_stage", rel_path, f"Invalid Lifecycle-Stage: {stage}"))
    canonical = record.get("canonical")
    if not isinstance(canonical, bool):
        findings.append(Finding("error", "invalid_canonical", rel_path, "Canonical must be exactly 'true' or 'false'."))
    for field in DATE_FIELDS:
        normalized_field = field.lower().replace("-", "_")
        value = record.get(normalized_field)
        if not value:
            continue
        if not isinstance(value, str):
            findings.append(Finding("error", "invalid_date_field", rel_path, f"{field} must be a string date."))
            continue
        try:
            parse_iso_date(value)
        except ValueError:
            findings.append(Finding("error", "invalid_date_format", rel_path, f"{field} must use YYYY-MM-DD."))
    summary = record.get("summary")
    if isinstance(summary, str) and len(summary) > 200:
        findings.append(Finding("warning", "summary_too_long", rel_path, "Summary exceeds 200 characters."))
    return findings


def iter_doc_paths(root: Path) -> Iterable[Path]:
    for rel_dir in SCANNED_DOC_DIRS:
        base = root / rel_dir
        if not base.exists():
            continue
        for path in sorted(base.rglob("*.md")):
            if is_current_tree_path(path.relative_to(root)):
                continue
            yield path


def canonical_active_source_records(records: list[dict[str, object]], *, stage: str | None = None, doc_id: str | None = None) -> list[dict[str, object]]:
    selected: list[dict[str, object]] = []
    for record in records:
        if record.get("header_status") != "valid":
            continue
        if record.get("canonical") is not True:
            continue
        if record.get("status") != "active":
            continue
        path = record.get("path")
        if not isinstance(path, str):
            continue
        if stage and record.get("lifecycle_stage") != stage:
            continue
        if doc_id and record.get("doc_id") != doc_id:
            continue
        if is_current_tree_path(Path(path)):
            continue
        if stage_root_for_record(record) is None:
            continue
        selected.append(record)
    return selected


def category_exists(stage_root: str, category: str) -> bool:
    return category in CURRENT_TAXONOMY.get(stage_root, ())


def contains_any(haystack: str, needles: tuple[str, ...]) -> bool:
    return any(needle in haystack for needle in needles)


def resolve_current_category(record: dict[str, object]) -> str:
    stage_root = stage_root_for_record(record)
    if stage_root is None:
        return "overview"
    doc_type = str(record.get("doc_type", ""))
    title = str(record.get("title", "")).lower()
    path = str(record.get("path", "")).lower()
    corpus = f"{title} {path}"

    if stage_root == "docs/2_Design":
        if doc_type == "component-spec":
            return "components"
        if doc_type == "contract":
            return "contracts"
        if doc_type == "policy":
            return "policy"
        if "contract" in corpus:
            return "contracts"
        if contains_any(corpus, ("policy", "governance", "rule", "rules", "vocabulary", "template")):
            return "policy"
        if contains_any(corpus, ("diagram", "sequence")):
            return "diagrams"
        if "flow" in corpus:
            return "flows"
        if contains_any(corpus, ("mapping", "consistency")):
            return "mappings"
        if contains_any(corpus, ("system", "lifecycle", "hub", "decomposition")):
            return "system"
        return "overview"

    if doc_type == "policy" and category_exists(stage_root, "policy"):
        return "policy"
    if doc_type == "component-spec" and category_exists(stage_root, "components"):
        return "components"
    if doc_type == "contract" and category_exists(stage_root, "contracts"):
        return "contracts"
    if "contract" in corpus and category_exists(stage_root, "contracts"):
        return "contracts"
    if contains_any(corpus, ("policy", "governance", "rule", "rules", "vocabulary")) and category_exists(stage_root, "policy"):
        return "policy"
    if doc_type in {"validation-note", "proof"}:
        if stage_root == "docs/5_Test" and category_exists(stage_root, "proofs"):
            return "proofs"
        if category_exists(stage_root, "reports"):
            return "reports"
    if doc_type == "glossary" and category_exists(stage_root, "glossary"):
        return "glossary"
    if contains_any(corpus, ("diagram", "sequence")) and category_exists(stage_root, "diagrams"):
        return "diagrams"
    if "flow" in corpus and category_exists(stage_root, "flows"):
        return "flows"
    if contains_any(corpus, ("mapping", "consistency")) and category_exists(stage_root, "mappings"):
        return "mappings"
    if "roadmap" in corpus and category_exists(stage_root, "roadmap"):
        return "roadmap"
    if "backlog" in corpus and category_exists(stage_root, "backlog"):
        return "backlog"
    if "runbook" in corpus and category_exists(stage_root, "runbooks"):
        return "runbooks"
    if contains_any(corpus, ("monitor", "operation", "ops")) and category_exists(stage_root, "operations"):
        return "operations"
    if "report" in corpus and category_exists(stage_root, "reports"):
        return "reports"
    if "packet" in corpus and category_exists(stage_root, "packets"):
        return "packets"
    if contains_any(corpus, ("overview", "lifecycle", "system")):
        if stage_root == "docs/2_Design" and category_exists(stage_root, "system"):
            return "system"
        if category_exists(stage_root, "overview"):
            return "overview"
    return "overview" if category_exists(stage_root, "overview") else CURRENT_TAXONOMY[stage_root][0]


def stable_filename_for_record(record: dict[str, object]) -> str:
    path = str(record.get("path", ""))
    filename = Path(path).name
    return DATE_PREFIX_RE.sub("", filename)


def current_target_relative_path(record: dict[str, object]) -> str:
    stage_root = stage_root_for_record(record)
    if stage_root is None:
        raise ValueError(f"Cannot resolve stage root for record path: {record.get('path')}")
    category = resolve_current_category(record)
    return str(Path(stage_root) / CURRENT_DIR_NAME / category / stable_filename_for_record(record))


def render_generated_current_copy(record: dict[str, object], root: Path) -> str:
    source_path = str(record.get("path"))
    source_text = (root / source_path).read_text(encoding="utf-8")
    banner = CURRENT_BANNER_TEMPLATE.format(source_path=source_path)
    return f"{banner}{source_text}"


def parse_current_banner(text: str) -> tuple[str | None, str]:
    if not text.startswith(CURRENT_BANNER_PREFIX):
        return None, text
    marker = "<!-- Do not edit this file directly; edit the dated source document and resync. -->"
    marker_index = text.find(marker)
    if marker_index == -1:
        return None, text
    banner_end = marker_index + len(marker)
    remainder = text[banner_end:]
    if remainder.startswith("\n\n"):
        remainder = remainder[2:]
    elif remainder.startswith("\n"):
        remainder = remainder[1:]
    source_match = re.search(r"^<!-- Source: (?P<source>.+) -->$", text, flags=re.MULTILINE)
    source_path = source_match.group("source").strip() if source_match else None
    return source_path, remainder


def sync_status_for_record(record: dict[str, object], root: Path) -> tuple[str, list[str]]:
    target_rel = current_target_relative_path(record)
    target_path = root / target_rel
    notes: list[str] = []
    if not target_path.exists():
        return "missing", notes
    target_text = target_path.read_text(encoding="utf-8")
    banner_source, remainder = parse_current_banner(target_text)
    expected_source = str(record.get("path"))
    if banner_source != expected_source:
        notes.append("generated banner source path does not match expected source")
        return "stale", notes
    source_text = (root / expected_source).read_text(encoding="utf-8")
    if remainder != source_text:
        notes.append("generated current copy content differs from source document")
        return "stale", notes
    return "in_sync", notes


def collision_record(record: dict[str, object], current_path: str, other_source_path: str) -> dict[str, object]:
    return {
        "doc_id": record.get("doc_id"),
        "title": record.get("title"),
        "doc_type": record.get("doc_type"),
        "status": record.get("status"),
        "lifecycle_stage": record.get("lifecycle_stage"),
        "component": record.get("component"),
        "domain": record.get("domain"),
        "canonical": record.get("canonical"),
        "source_path": record.get("path"),
        "current_path": current_path,
        "current_category": resolve_current_category(record),
        "source_last_edited": record.get("last_edited"),
        "current_exists": False,
        "sync_status": "collision",
        "notes": [f"target collides with source {other_source_path}"],
    }


def snapshot_payload(root: Path, records: list[dict[str, object]], *, stage: str | None = None, doc_id: str | None = None) -> dict[str, object]:
    sources = canonical_active_source_records(records, stage=stage, doc_id=doc_id)
    records_out: list[dict[str, object]] = []
    target_to_source: dict[str, str] = {}
    collision_count = 0
    missing_count = 0
    stale_count = 0
    for record in sources:
        current_path = current_target_relative_path(record)
        other_source = target_to_source.get(current_path)
        if other_source is not None:
            collision_count += 1
            records_out.append(collision_record(record, current_path, other_source))
            continue
        target_to_source[current_path] = str(record.get("path"))
        sync_status, notes = sync_status_for_record(record, root)
        if sync_status == "missing":
            missing_count += 1
        elif sync_status == "stale":
            stale_count += 1
        records_out.append(
            {
                "doc_id": record.get("doc_id"),
                "title": record.get("title"),
                "doc_type": record.get("doc_type"),
                "status": record.get("status"),
                "lifecycle_stage": record.get("lifecycle_stage"),
                "component": record.get("component"),
                "domain": record.get("domain"),
                "canonical": record.get("canonical"),
                "source_path": record.get("path"),
                "current_path": current_path,
                "current_category": resolve_current_category(record),
                "source_last_edited": record.get("last_edited"),
                "current_exists": sync_status != "missing",
                "sync_status": sync_status,
                "notes": notes,
            }
        )
    return {
        "generated_at": now_iso(),
        "root": str(root),
        "summary": {
            "canonical_active_source_count": len(sources),
            "current_target_count": len(target_to_source),
            "collision_count": collision_count,
            "missing_current_count": missing_count,
            "stale_current_count": stale_count,
        },
        "records": records_out,
    }


def render_snapshot_table(payload: dict[str, object]) -> str:
    records = payload.get("records", [])
    if not isinstance(records, list) or not records:
        return "No records found."
    columns = ["current_path", "source_path", "doc_id", "doc_type", "component", "source_last_edited", "sync_status"]
    widths = {col: len(col) for col in columns}
    rows: list[list[str]] = []
    for record in records:
        row = [format_cell(record.get(col)) for col in columns]
        rows.append(row)
        for col, value in zip(columns, row):
            widths[col] = max(widths[col], len(value))
    header = "  ".join(col.ljust(widths[col]) for col in columns)
    sep = "  ".join("-" * widths[col] for col in columns)
    body = ["  ".join(value.ljust(widths[col]) for value, col in zip(row, columns)) for row in rows]
    return "\n".join([header, sep, *body])


def render_snapshot_markdown(payload: dict[str, object]) -> str:
    summary = payload.get("summary", {})
    records = payload.get("records", [])
    lines = ["# Current Authority Snapshot", ""]
    lines.append(f"Generated at: `{payload.get('generated_at', '')}`")
    lines.append("")
    lines.append("## Summary")
    lines.append("")
    lines.append(f"- canonical active source count: `{summary.get('canonical_active_source_count', 0)}`")
    lines.append(f"- current target count: `{summary.get('current_target_count', 0)}`")
    lines.append(f"- collision count: `{summary.get('collision_count', 0)}`")
    lines.append(f"- missing current count: `{summary.get('missing_current_count', 0)}`")
    lines.append(f"- stale current count: `{summary.get('stale_current_count', 0)}`")
    lines.append("")
    if not isinstance(records, list) or not records:
        lines.append("No records found.")
        return "\n".join(lines) + "\n"
    grouped: dict[str, list[dict[str, object]]] = {}
    for record in records:
        stage = str(record.get("lifecycle_stage", "unknown"))
        grouped.setdefault(stage, []).append(record)
    for stage in sorted(grouped):
        lines.append(f"## {stage}")
        lines.append("")
        lines.append("| Current Path | Source Path | Doc-ID | Type | Component | Last-Edited | Sync Status |")
        lines.append("|---|---|---|---|---|---|---|")
        for record in grouped[stage]:
            lines.append(
                "| "
                + " | ".join(
                    [
                        str(record.get("current_path", "")),
                        str(record.get("source_path", "")),
                        str(record.get("doc_id", "")),
                        str(record.get("doc_type", "")),
                        str(record.get("component", "")),
                        str(record.get("source_last_edited", "")),
                        str(record.get("sync_status", "")),
                    ]
                )
                + " |"
            )
        lines.append("")
    return "\n".join(lines)


def build_index(root: Path) -> tuple[list[dict[str, object]], list[Finding]]:
    records: list[dict[str, object]] = []
    findings: list[Finding] = []
    for path in iter_doc_paths(root):
        record, record_findings = parse_header(path, root)
        findings.extend(record_findings)
        if record is not None:
            records.append(record)
        else:
            records.append({
                "path": repo_relative(path, root),
                "header_status": "legacy_missing_header" if any(f.code == "legacy_missing_header" for f in record_findings) else "invalid_header",
            })
    findings.extend(validate_index(records))
    return records, findings


def group_key(record: dict[str, object]) -> tuple[object, object, object]:
    return (record.get("component"), record.get("doc_type"), record.get("lifecycle_stage"))


def validate_index(records: list[dict[str, object]]) -> list[Finding]:
    findings: list[Finding] = []
    seen_doc_ids: dict[str, str] = {}
    canonical_groups: dict[tuple[object, object, object], list[str]] = {}
    path_lookup = {str(record.get("path")): record for record in records}
    file_name_lookup = {Path(str(record.get("path"))).name: str(record.get("path")) for record in records}
    for record in records:
        rel_path = str(record.get("path"))
        if record.get("header_status") == "legacy_missing_header":
            continue
        doc_id = record.get("doc_id")
        if isinstance(doc_id, str):
            previous = seen_doc_ids.get(doc_id)
            if previous and previous != rel_path:
                findings.append(Finding("error", "duplicate_doc_id", rel_path, f"Doc-ID duplicates {previous}"))
            else:
                seen_doc_ids[doc_id] = rel_path
        if record.get("canonical") is True:
            canonical_groups.setdefault(group_key(record), []).append(rel_path)
        if record.get("status") == "superseded" and record.get("canonical") is True:
            findings.append(Finding("warning", "canonical_superseded", rel_path, "Superseded document should not be canonical."))
        for field_name in ("depends_on", "supersedes", "superseded_by"):
            references = record.get(field_name) or []
            if not isinstance(references, list):
                continue
            for ref in references:
                if ref in path_lookup:
                    continue
                if Path(ref).name in file_name_lookup:
                    continue
                findings.append(Finding("warning", "unresolved_reference", rel_path, f"{field_name} reference does not resolve: {ref}"))
        for field_name in ("review_after", "expires"):
            value = record.get(field_name)
            if isinstance(value, str):
                try:
                    if parse_iso_date(value) < date.today():
                        findings.append(Finding("warning", "stale_review", rel_path, f"{field_name.replace('_', '-').title()} is in the past."))
                except ValueError:
                    pass
    for key, paths in canonical_groups.items():
        if len(paths) > 1 and key != (None, None, None):
            for rel_path in paths:
                findings.append(Finding("warning", "canonical_ambiguity", rel_path, f"Multiple canonical docs share component/doc-type/lifecycle-stage group {key}."))
    return findings


def filter_records(records: list[dict[str, object]], args: argparse.Namespace) -> list[dict[str, object]]:
    results: list[dict[str, object]] = []
    for record in records:
        if record.get("header_status") == "legacy_missing_header" and not getattr(args, "include_legacy", False):
            continue
        if getattr(args, "doc_id", None) and record.get("doc_id") != args.doc_id:
            continue
        if getattr(args, "title_contains", None):
            title = str(record.get("title", "")).lower()
            if args.title_contains.lower() not in title:
                continue
        if getattr(args, "doc_type", None) and record.get("doc_type") != args.doc_type:
            continue
        if getattr(args, "status", None) and record.get("status") != args.status:
            continue
        if getattr(args, "stage", None) and record.get("lifecycle_stage") != args.stage:
            continue
        if getattr(args, "component", None) and record.get("component") != args.component:
            continue
        if getattr(args, "domain", None) and record.get("domain") != args.domain:
            continue
        if getattr(args, "keyword", None):
            keywords = record.get("keywords") or []
            if args.keyword not in keywords:
                continue
        if getattr(args, "canonical", None) is not None and record.get("canonical") is not args.canonical:
            continue
        if getattr(args, "path_prefix", None) and not str(record.get("path", "")).startswith(args.path_prefix):
            continue
        results.append(record)
    return results


def current_records(records: list[dict[str, object]], args: argparse.Namespace) -> list[dict[str, object]]:
    filtered = filter_records(records, args)
    filtered = [r for r in filtered if r.get("status") != "superseded" and r.get("header_status") == "valid"]
    canonicals = [r for r in filtered if r.get("canonical") is True]
    return canonicals or filtered


def related_payload(records: list[dict[str, object]], args: argparse.Namespace) -> dict[str, object]:
    target = None
    for record in records:
        if args.doc_id and record.get("doc_id") == args.doc_id:
            target = record
            break
        if args.path and record.get("path") == args.path:
            target = record
            break
    if target is None:
        raise SystemExit("No matching document found for related lookup.")
    def matches_same(field: str) -> list[dict[str, object]]:
        value = target.get(field)
        if not value:
            return []
        return [r for r in records if r is not target and r.get(field) == value and r.get("header_status") == "valid"]
    return {
        "target": target,
        "depends_on": target.get("depends_on", []),
        "supersedes": target.get("supersedes", []),
        "superseded_by": target.get("superseded_by", []),
        "same_component": matches_same("component"),
        "same_domain": matches_same("domain"),
        "same_lifecycle_stage": matches_same("lifecycle_stage"),
    }


def stale_records(records: list[dict[str, object]], findings: list[Finding], canonical_only: bool) -> list[dict[str, object]]:
    stale_paths = {
        finding.path
        for finding in findings
        if finding.severity in {"warning", "error"}
        and finding.code in {"stale_review", "canonical_superseded", "unresolved_reference", "invalid_header", "missing_required_field", "duplicate_doc_id"}
    }
    results = []
    for record in records:
        if str(record.get("path")) not in stale_paths:
            continue
        if canonical_only and record.get("canonical") is not True:
            continue
        results.append(record)
    return results


def render_table(records: list[dict[str, object]]) -> str:
    if not records:
        return "No records found."
    columns = ["path", "doc_type", "status", "lifecycle_stage", "component", "domain", "canonical", "header_status"]
    widths = {col: len(col) for col in columns}
    rows: list[list[str]] = []
    for record in records:
        row = [format_cell(record.get(col)) for col in columns]
        rows.append(row)
        for col, value in zip(columns, row):
            widths[col] = max(widths[col], len(value))
    header = "  ".join(col.ljust(widths[col]) for col in columns)
    sep = "  ".join("-" * widths[col] for col in columns)
    body = ["  ".join(value.ljust(widths[col]) for value, col in zip(row, columns)) for row in rows]
    return "\n".join([header, sep, *body])


def format_cell(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list):
        return ", ".join(str(item) for item in value)
    return "" if value is None else str(value)


