@dataclass
class Finding:
    severity: str
    code: str
    path: str
    message: str

    def to_dict(self) -> dict[str, str]:
        return {
            "severity": self.severity,
            "code": self.code,
            "path": self.path,
            "message": self.message,
        }


def parse_iso_date(value: str) -> date:
    return date.fromisoformat(value)


def repo_relative(path: Path, root: Path) -> str:
    try:
        return str(path.relative_to(root))
    except ValueError:
        return str(path)


def today_iso() -> str:
    return date.today().isoformat()


def now_iso() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def is_current_tree_path(path: Path) -> bool:
    return CURRENT_DIR_NAME in path.parts


def stage_root_for_path(path: str) -> str | None:
    normalized = path.replace("\\", "/")
    for stage_root in CURRENT_TAXONOMY:
        if normalized == stage_root or normalized.startswith(f"{stage_root}/"):
            return stage_root
    return None


def stage_root_for_record(record: dict[str, object]) -> str | None:
    path = record.get("path")
    if not isinstance(path, str):
        return None
    return stage_root_for_path(path)


def infer_title_from_path(path: Path) -> str:
    stem = path.stem
    stem = re.sub(r"^\d{4}-\d{2}-\d{2}-", "", stem)
    stem = stem.replace("-", " ").replace("_", " ").strip()
    return " ".join(word.capitalize() if word.islower() else word for word in stem.split()) or path.stem


def slugify_title(title: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
    return slug or "untitled-doc"


